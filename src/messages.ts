/** The ultra-charge progress message (a 5-cell bar plus percentage). */
export function ultraChargeText(percent: number): string {
  const filledCount = Math.floor(percent / 20);
  const emptyCount = 5 - filledCount;
  const bar = `${'🟩'.repeat(filledCount)}${'⬛'.repeat(emptyCount)}`;
  const caption = percent === 100 ? 'Лови маслину' : 'Зарядка мега-хрептины';

  return `${bar} ${percent}%\n${caption}`;
}

/** One frame of the `lef` bureaucracy animation. */
export function lefFrameText(
  target: ResolvedTarget,
  variant: string,
  frame: string,
  index: number,
): string {
  return [
    frame,
    '',
    `Цель: ${target.label}`,
    `Тип: ${variant}`,
    `Прогресс: ${index}/${LEF_ANIMATION_FRAMES.length}`,
  ].join('\n');
}
